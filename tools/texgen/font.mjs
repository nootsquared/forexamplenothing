export function generateFontSheet() {
  const { canvas, ctx } = makeCanvas(CELL_W * GLYPHS.length, CELL_H);
  for (let i = 0; i < GLYPHS.length; i++) {
    const rows = ROWS[GLYPHS[i]];
    const grid = new PixelGrid(CELL_W, CELL_H);
    rows.forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') grid.set(x + 1, y + 1, '#ffffff');
    });
    grid.autoOutline('#1a1626');
    grid.blitTo(ctx, i * CELL_W, 0);
  }
  return canvas;
}

// Stamp a word directly onto another canvas (used by the ad boards)
export function stampText(ctx, text, x, y, color, scale = 1) {
  for (let i = 0; i < text.length; i++) {
    const rows = ROWS[text[i]];
    if (!rows) continue; // space
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < 5; rx++) {
        if (row[rx] === '#') {
          ctx.fillStyle = color;
          ctx.fillRect(x + (i * 6 + rx) * scale, y + ry * scale, scale, scale);
        }
      }
    });
  }
}

export function textWidth(text, scale = 1) {
  return (text.length * 6 - 1) * scale;
}
